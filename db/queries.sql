-- QUERY 1: Passenger booking history
-- This query displays all bookings made by a passenger.
-- It retrieves the booking date, journey details, stations and segment prices.

SELECT
    p.passenger_id,
    p.first_name,
    p.last_name,
    b.booking_id,
    b.booked_at,
    b.total_price,
    tt.trip_number,
    r.run_date,
    departure_station.name AS departure_station,
    arrival_station.name AS arrival_station,
    bs.price AS segment_price
FROM passenger p
JOIN booking b
    ON b.passenger_id = p.passenger_id
JOIN booking_segment bs
    ON bs.booking_id = b.booking_id
JOIN run r
    ON r.run_id = bs.run_id
JOIN train_trip tt
    ON tt.trip_id = r.trip_id
JOIN station departure_station
    ON departure_station.station_id = bs.departure_station_id
JOIN station arrival_station
    ON arrival_station.station_id = bs.arrival_station_id
WHERE p.email = 'passenger@example.com'
ORDER BY b.booked_at DESC;


-- QUERY 2: Train timetable
-- This query displays the timetable of a train trip on a selected date.
-- It lists every station in the correct order with its arrival and departure times.

SELECT
    tt.trip_number,
    r.run_date,
    st.stop_sequence,
    s.name AS station_name,
    st.arrival_time,
    st.departure_time
FROM train_trip tt
JOIN run r
    ON r.trip_id = tt.trip_id
JOIN stop_time st
    ON st.trip_id = tt.trip_id
JOIN station s
    ON s.station_id = st.station_id
WHERE tt.trip_number = 'TRIP-8820'
  AND r.run_date = DATE '2026-11-10'
ORDER BY st.stop_sequence;


-- QUERY 3: Available seats between two stations
-- This query finds the seats available for a journey between two selected stations.
-- It excludes seats that are already reserved on at least one section of the requested route.

WITH requested_route AS (
    SELECT
        r.run_id,
        tt.trip_id,
        tt.train_id,
        departure.stop_sequence AS departure_sequence,
        arrival.stop_sequence AS arrival_sequence
    FROM run r
    JOIN train_trip tt
        ON tt.trip_id = r.trip_id
    JOIN stop_time departure
        ON departure.trip_id = tt.trip_id
    JOIN station departure_station
        ON departure_station.station_id = departure.station_id
    JOIN stop_time arrival
        ON arrival.trip_id = tt.trip_id
    JOIN station arrival_station
        ON arrival_station.station_id = arrival.station_id
    WHERE tt.trip_number = 'TRIP-8820'
      AND r.run_date = DATE '2026-11-10'
      AND departure_station.code = 'MAR'
      AND arrival_station.code = 'LYO'
      AND departure.stop_sequence < arrival.stop_sequence
)
SELECT
    rr.run_id,
    c.carriage_number,
    s.seat_number,
    tc.label AS travel_class
FROM requested_route rr
JOIN carriage c
    ON c.train_id = rr.train_id
JOIN seat s
    ON s.carriage_id = c.carriage_id
JOIN travel_class tc
    ON tc.travel_class_id = s.travel_class_id
WHERE NOT EXISTS (
    SELECT 1
    FROM reserved_leg rl
    JOIN stop_time occupied_stop
        ON occupied_stop.trip_id = rr.trip_id
       AND occupied_stop.station_id = rl.station_id
    WHERE rl.run_id = rr.run_id
      AND rl.seat_id = s.seat_id
      AND occupied_stop.stop_sequence >= rr.departure_sequence
      AND occupied_stop.stop_sequence < rr.arrival_sequence
)
ORDER BY c.carriage_number, s.seat_number;


-- QUERY 4: Booking statistics by train
-- This query calculates the number of bookings and the revenue generated by each train.
-- It also includes trains that do not have any bookings.

SELECT
    t.train_number,
    COUNT(DISTINCT b.booking_id) AS booking_count,
    COUNT(DISTINCT bs.booking_segment_id) AS segment_count,
    COALESCE(SUM(bs.price), 0) AS total_revenue
FROM train t
LEFT JOIN train_trip tt
    ON tt.train_id = t.train_id
LEFT JOIN run r
    ON r.trip_id = tt.trip_id
LEFT JOIN booking_segment bs
    ON bs.run_id = r.run_id
LEFT JOIN booking b
    ON b.booking_id = bs.booking_id
GROUP BY t.train_id, t.train_number
ORDER BY total_revenue DESC;


-- QUERY 5: Monthly booking statistics
-- This query displays the number of bookings made during each month.
-- It calculates the total revenue generated by bookings for each month.

SELECT
    DATE_TRUNC('month', booked_at) AS booking_month,
    COUNT(booking_id) AS booking_count,
    SUM(total_price) AS total_revenue
FROM booking
GROUP BY DATE_TRUNC('month', booked_at)
ORDER BY booking_month;


-- QUERY 6: Journey with one transfer
-- This query searches for journeys between two stations with exactly one transfer.
-- It checks that both trains run on the same date and that the transfer takes at least ten minutes.

WITH first_leg AS (
    SELECT
        r.run_date,
        r.run_id,
        tt.trip_id,
        tt.train_id,
        tt.trip_number,
        t.train_number,
        departure_station.name AS departure_station,
        transfer_station.station_id AS transfer_station_id,
        transfer_station.name AS transfer_station,
        departure.departure_time AS first_departure_time,
        transfer.arrival_time AS transfer_arrival_time
    FROM run r
    JOIN train_trip tt
        ON tt.trip_id = r.trip_id
    JOIN train t
        ON t.train_id = tt.train_id
    JOIN stop_time departure
        ON departure.trip_id = tt.trip_id
    JOIN station departure_station
        ON departure_station.station_id = departure.station_id
    JOIN stop_time transfer
        ON transfer.trip_id = tt.trip_id
       AND transfer.stop_sequence > departure.stop_sequence
    JOIN station transfer_station
        ON transfer_station.station_id = transfer.station_id
    WHERE departure_station.code = 'MAR'
      AND r.run_date = DATE '2026-11-10'
),
second_leg AS (
    SELECT
        r.run_date,
        r.run_id,
        tt.trip_id,
        tt.train_id,
        tt.trip_number,
        t.train_number,
        transfer.station_id AS transfer_station_id,
        transfer_station.name AS transfer_station,
        arrival_station.name AS arrival_station,
        transfer.departure_time AS second_departure_time,
        arrival.arrival_time AS second_arrival_time
    FROM run r
    JOIN train_trip tt
        ON tt.trip_id = r.trip_id
    JOIN train t
        ON t.train_id = tt.train_id
    JOIN stop_time transfer
        ON transfer.trip_id = tt.trip_id
    JOIN station transfer_station
        ON transfer_station.station_id = transfer.station_id
    JOIN stop_time arrival
        ON arrival.trip_id = tt.trip_id
       AND arrival.stop_sequence > transfer.stop_sequence
    JOIN station arrival_station
        ON arrival_station.station_id = arrival.station_id
    WHERE arrival_station.code = 'LYO'
      AND r.run_date = DATE '2026-11-10'
)
SELECT
    f.departure_station,
    f.train_number AS first_train,
    f.first_departure_time,
    f.transfer_station,
    f.transfer_arrival_time,
    s.train_number AS second_train,
    s.second_departure_time,
    s.arrival_station,
    s.second_arrival_time,
    f.run_date
FROM first_leg f
JOIN second_leg s
    ON s.transfer_station_id = f.transfer_station_id
   AND s.run_date = f.run_date
   AND s.run_id <> f.run_id
   AND s.train_id <> f.train_id
WHERE s.second_departure_time >=
      f.transfer_arrival_time + INTERVAL '10 minutes'
ORDER BY f.first_departure_time, s.second_departure_time;